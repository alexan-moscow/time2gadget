namespace Time2Gadget.Models;

/// <summary>
/// Визуальный эффект циферблата при ЗАВЕРШЕНИИ таймера (пока звонит будильник) — отдельно от
/// RunningVisualEffect (эффект во время отсчёта). По умолчанию отключён. Докладка 2026-09-27.
/// </summary>
public enum FinishVisualEffect
{
    None,
    Pulse,      // ритмичное увеличение кольца + красно-оранжевая подсветка
    Flash,      // резкие короткие вспышки (строб)
    ColorCycle, // плавная цикличная "волна" цвета красный→янтарный→красный
    // Докладка 2026-09-28 (в конец — сохранённые значения в settings.json не сдвигаются):
    Waves,       // встречные волны: по кольцу секторов (полный вид) / по краю окна (компакт)
    Snake,       // узкая змейка бежит по рамке окна
    RainbowSnake // яркая радужная змейка по рамке со свечением
}
